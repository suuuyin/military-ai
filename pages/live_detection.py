import streamlit as st
from ultralytics import YOLO
import cv2
import numpy as np
from pathlib import Path
from PIL import Image


# =========================================================
# 頁面設定
# =========================================================
st.set_page_config(
    page_title="即時偵測",
    page_icon="📡",
    layout="wide"
)


# =========================================================
# 模型位置
# =========================================================
BASE_DIR = Path(__file__).resolve().parent.parent
MODEL_PATH = BASE_DIR / "best.pt"


# =========================================================
# 載入 YOLO 模型
# =========================================================
@st.cache_resource
def load_model():
    return YOLO(str(MODEL_PATH))


# =========================================================
# 標題
# =========================================================
st.title("即時偵測")

st.write(
    "使用攝影機進行 AI 軍事目標即時辨識與分析"
)


# =========================================================
# 載入模型
# =========================================================
try:
    model = load_model()

    st.success("AI 模型已就緒")

except Exception as e:
    st.error(f"模型載入失敗：{e}")
    st.stop()


# =========================================================
# 顯示模型資訊
# =========================================================
with st.expander("查看 AI 模型辨識類別"):
    st.write(model.names)


# =========================================================
# 攝影機
# =========================================================
st.subheader("即時影像來源")

camera_image = st.camera_input(
    "開啟攝影機並拍攝影像"
)


# =========================================================
# 有拍攝照片
# =========================================================
if camera_image is not None:

    # -----------------------------------------------------
    # Streamlit 圖片轉 PIL
    # -----------------------------------------------------
    image = Image.open(camera_image)

    image_np = np.array(image)


    # -----------------------------------------------------
    # 確保 RGB
    # -----------------------------------------------------
    if len(image_np.shape) == 2:

        image_np = cv2.cvtColor(
            image_np,
            cv2.COLOR_GRAY2RGB
        )


    # =====================================================
    # YOLO 辨識
    # =====================================================
    with st.spinner("正在進行即時辨識..."):

        results = model.predict(
            image_np,
            conf=0.25,
            verbose=False
        )


    result = results[0]


    # =====================================================
    # YOLO 畫 Bounding Box
    # =====================================================
    plotted = result.plot()

    plotted_rgb = cv2.cvtColor(
        plotted,
        cv2.COLOR_BGR2RGB
    )


    # =====================================================
    # 統計
    # =====================================================
    class_counts = {
        "aeroplane": 0,
        "military vehicle": 0,
        "person": 0,
        "tank": 0,
        "warship": 0
    }

    confidences = []

    detection_data = []


    # =====================================================
    # 取得 Bounding Box
    # =====================================================
    if (
        result.boxes is not None
        and len(result.boxes) > 0
    ):

        for box in result.boxes:

            # ---------------------------------------------
            # 類別
            # ---------------------------------------------
            cls_id = int(
                box.cls[0].item()
            )

            cls_name = str(
                model.names[cls_id]
            ).lower()


            # ---------------------------------------------
            # Confidence
            # ---------------------------------------------
            confidence = float(
                box.conf[0].item()
            )

            confidences.append(
                confidence
            )


            # ---------------------------------------------
            # 統計類別
            # ---------------------------------------------
            if cls_name in class_counts:

                class_counts[
                    cls_name
                ] += 1


            # ---------------------------------------------
            # Bounding Box 座標
            # ---------------------------------------------
            x1, y1, x2, y2 = (
                box.xyxy[0].tolist()
            )


            # ---------------------------------------------
            # 儲存詳細資料
            # ---------------------------------------------
            detection_data.append(
                {
                    "辨識類別":
                        cls_name,

                    "Confidence":
                        round(
                            confidence * 100,
                            1
                        ),

                    "X1":
                        round(x1, 1),

                    "Y1":
                        round(y1, 1),

                    "X2":
                        round(x2, 1),

                    "Y2":
                        round(y2, 1)
                }
            )


# =========================================================
# 顯示結果
# =========================================================
    st.divider()

    st.header("即時分析結果")


# =========================================================
# 左邊影像 / 右邊分析
# =========================================================
    image_col, analysis_col = st.columns(
        [2, 1]
    )


# =========================================================
# 左邊
# =========================================================
    with image_col:

        st.subheader("AI 偵測畫面")

        st.image(
            plotted_rgb,
            use_container_width=True
        )


# =========================================================
# 右邊
# =========================================================
    with analysis_col:

        st.subheader("目前畫面統計")


        # -------------------------------------------------
        # 人員
        # -------------------------------------------------
        st.metric(
            "人員",
            class_counts["person"]
        )


        # -------------------------------------------------
        # 所有目標
        # -------------------------------------------------
        total_objects = sum(
            class_counts.values()
        )

        st.metric(
            "偵測物件總數",
            total_objects
        )


        # -------------------------------------------------
        # Confidence
        # -------------------------------------------------
        if confidences:

            avg_conf = np.mean(
                confidences
            )

            st.metric(
                "平均 Confidence",
                f"{avg_conf * 100:.1f}%"
            )

        else:

            st.metric(
                "平均 Confidence",
                "—"
            )


# =========================================================
# 五種類別
# =========================================================
    st.subheader("目標類別統計")

    col1, col2, col3, col4, col5 = (
        st.columns(5)
    )


    col1.metric(
        "人員",
        class_counts["person"]
    )

    col2.metric(
        "飛機",
        class_counts["aeroplane"]
    )

    col3.metric(
        "軍用車輛",
        class_counts["military vehicle"]
    )

    col4.metric(
        "戰車",
        class_counts["tank"]
    )

    col5.metric(
        "軍艦",
        class_counts["warship"]
    )


# =========================================================
# 偵測結果提示
# =========================================================
    if class_counts["person"] > 0:

        st.success(
            f"目前畫面偵測到 "
            f"{class_counts['person']} 人"
        )


    if total_objects == 0:

        st.warning(
            "目前畫面沒有偵測到目標"
        )


# =========================================================
# 詳細資料
# =========================================================
    if detection_data:

        st.subheader(
            "偵測物件明細"
        )

        st.dataframe(
            detection_data,
            use_container_width=True
        )


# =========================================================
# 返回首頁
# =========================================================
st.divider()

if st.button("← 返回首頁"):
    st.switch_page("app.py")